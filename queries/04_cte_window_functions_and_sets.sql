/*
Задание 1
Службе ИТ-мониторинга необходимо составить хронологический лог всех действий пользователей в системе 
за определенный период для оценки нагрузки на серверную инфраструктуру. 
На основе таблицы журналов событий рейса (history) и таблицы посадочных талонов (boarding) 
сформируйте единый реестр зафиксированных операций за период с 10 по 12 августа 2026 года включительно. 
Итоговая таблица должна содержать два столбца: точную дату-время проведения операции и текстовый тип события. 
Для записей из первой таблицы в поле типа события выведите текстовое значение «Изменение статуса рейса», 
а для записей из второй таблицы – «Выдача посадочного талона».
*/
select status_time, ('Изменение статуса рейса') as type from history
where status_time between '2026-08-10 00:00:00' and '2026-08-12 23:59:59'
union
select registration_time, ('Выдача посадочного талона') as type from boarding
where registration_time between '2026-08-10 00:00:00' and '2026-08-12 23:59:59';

/*
Задание 2
Департамент маркетинга ищет лояльных клиентов для закрытого опроса о качестве семейных перевозок. 
Аналитикам нужно найти взрослых пассажиров, которые не просто летают сами, но и оплачивают билеты для детей. 
На основе таблицы пассажиров (passenger) и таблицы билетов (ticket) найдите пересечение двух списков. 
В первый список включите ФИО всех клиентов из категории «Взрослый», на которых были оформлены авиабилеты. 
Во второй список включите ФИО клиентов, 
которые выступили покупателями билетов для пассажиров из категории «Ребенок».
*/

select full_name from passenger
where category_name = 'Взрослый'
intersect
select p1.full_name from ticket t1 
join passenger p1 on p1.passenger_id = t1.passenger_id 
join ticket t2 on t2.booking_id = t1.booking_id and t2.passenger_id != t1.passenger_id
join passenger p2 on p2.passenger_id = t2.passenger_id
where p2.category_name = 'Ребенок';

/*
Задание 3
Отдел управления качеством сервиса анализирует эксплуатацию премиального фонда авиакомпании. 
Руководству необходимо выявить модели самолетов, на которых ни разу не летали пассажиры бизнес-класса. 
На основе таблицы самолетов (airplane), таблицы мест в салоне (seat) и 
