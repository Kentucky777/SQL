*/

select f.flight_id, r.route_no, a.brand, a.model, p.full_name, t.price, dense_rank() over (partition by f.flight_id order by t.price desc) as rn 
from flight f join airplane a on a.airplane_id = f.airplane_id 
join route r on r.route_id = f.route_id
join ticket t on t.flight_id = f.flight_id
join passenger p on p.passenger_id = t.passenger_id
where a.airplane_class = 'Среднемагистральный';

/*
Задание 12
