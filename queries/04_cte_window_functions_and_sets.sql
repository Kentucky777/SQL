данных на основе таблиц журналов событий рейса (history), вылетов (flight) и маршрутов (route) 
Ограничьте анализ рейсами, у которых аэропортом отправления является указанный авиаузел. 
Внутри временного слоя с помощью оконных функций смещения извлеките для каждой записи 
наименование предыдущего статуса и время его фиксации.
В основном запросе выведите идентификатор вылета (flight_id), номер рейса (route_no), 
текущий и предыдущий статусы, а также рассчитайте разницу в минутах между временем текущего 
и предыдущего события.

Примечание: Для расчёта разницы между двумя отметками времени можно использовать стандартную конструкцию: 
EXTRACT(EPOCH FROM (Время1 - Время2)).
Параметр EPOCH автоматически переводит полученный промежуток времени в секунды.

*/

with pulk as(
select f.flight_id, r.route_no ,h.status_name, h.status_time, 
lag(h.status_name) over(partition by f.flight_id order by h.status_time) as prev_status, 
lag(h.status_time) over(partition by f.flight_id order by h.status_time) as prev_time from history h
join flight f on f.flight_id = h.flight_id
join route r on r.route_id = f.route_id
where r.departure_airport_id = 131
)
select flight_id, route_no, status_name, prev_status, ceil(extract(epoch from(status_time - prev_time))/ 60) as diff from pulk;