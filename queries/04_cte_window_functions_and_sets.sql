/*
Задание 9
Финансово-экономическая служба формирует сводную ведомость продаж для анализа структуры доходов. 
Чтобы оценить масштабы каждой коммерческой операции, руководству необходимо сопоставить параметры 
каждого проданного билета с общими продажами предприятия. 
На основе таблиц билетов (ticket), вылетов (flight), маршрутов (route) и городов (city) 
выведите номер рейса (route_no), название города прилета и итоговую финальную стоимость билета (price). 
С помощью аналитической оконной функции с пустым окном рассчитайте и выведите в отдельном 
столбце общую сумму выручки от продажи абсолютно всех билетов авиакомпании.
Дополнительно вычислите долю (в процентах) стоимости текущего билета в общем объеме доходов компании.
*/

select r.route_no, c.city_name, t.price, sum(t.price) over() as amount,
round(100 * t.price/sum(price) over(),2) as percent from ticket t join flight f on f.flight_id = t.flight_id
join route r on r.route_id = f.route_id
join airport a on a.airport_id = r.arrival_airport_id
join city c on c.city_id = a.city_id;

/*
Задание 10
Коммерческий департамент отслеживает ежедневную динамику поступления денежных 
средств для оценки скорости заполняемости рейсов. Аналитикам необходим финансовый отчет, 
отображающий накопление выручки по дням за отчетный период. 
На основе таблиц билетов (ticket), вылетов (flight) и маршрутов (route) 
выведите номер рейса по расписанию (route_no), дату продажи билета (sale_date) и стоимость продажи (price). 
Ограничьте анализ продажами, совершенными в 3 квартале 2026 года. 
С помощью аналитической оконной функции рассчитайте кумулятивную сумму выручки, 
которая формируется нарастающим итогом по мере продажи билетов. 
Настройте окно так, чтобы этот накопительный итог 
рассчитывался отдельно для каждого номера рейса и увеличивался в хронологическом порядке дат продаж.
*/

select r.route_no, t.sale_date, t.price, 
sum(price) over(partition by route_no order by t.sale_date) as sum_revenue
from ticket t join flight f on f.flight_id = t.flight_id
join route r on r.route_id = f.route_id
where t.sale_date between '2026-07-01' and '2026-09-30'
order by t.sale_date;

/*
Задание 11
Служба тарифообразования анализирует структуру продаж на популярных направлениях для оценки 
эффективности действующих тарифных сеток. Аналитикам необходимо определить ранги стоимости билетов на рейсах, 
выполняемых лайнерами определенного класса. 
На основе таблиц билетов (ticket), вылетов (flight), маршрутов (route), самолетов (airplane) 
и пассажиров (passenger) выведите идентификатор вылета (flight_id), номер рейса (route_no), 
бренд и модель самолета, ФИО пассажира и итоговую финальную стоимость билета (price). 
Ограничьте итоговый отчет рейсами, которые выполняются на воздушных судах 
с классом магистральности 'Среднемагистральный'. 
С помощью функции ранжирования оконных функций присвойте ранг каждой продаже так, 
чтобы нумерация велась отдельно для каждого конкретного рейса в порядке убывания стоимости 
билетов (от дорогих к дешевым). При наличии билетов с одинаковой ценой в рамках одного рейса 
они должны получить одинаковый ранг, а следующий за ними номер ранга не должен прерываться.
