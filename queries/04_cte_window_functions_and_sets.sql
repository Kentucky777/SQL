/*
Задание 4
Служба организации перевозок оценивает операционную загрузку аэропортов вылета для оптимизации расписания 
наземных служб. 
Аналитикам необходимо определить авиаузлы, из которых отправляется наибольшее количество рейсов. 
Используя обобщенное табличное выражение, подготовьте временный слой на основе таблицы вылетов (flight) 
и таблицы маршрутов (route), рассчитав общее количество фактически
запланированных рейсов для каждого аэропорта вылета. 
В основном запросе, соединив этот слой с таблицей аэропортов (airport), 
выведите названия тех аэропортов, у которых количество вылетов превышает среднее количество рейсов, 
приходящееся на один работающий аэропорт компании.
*/

with dep_count as(
select r.departure_airport_id, count(*) as count_flight from flight f join route r on r.route_id = f.route_id
group by r.departure_airport_id
)
select a.airport_name from dep_count d join airport a on a.airport_id = d.departure_airport_id
where d.count_flight > (select avg(count_flight) from dep_count);

/*
Задание 5
Коммерческий департамент оценивает финансовую отдачу от эксплуатации действующих авиамаршрутов 
для выявления наименее прибыльных направлений. Аналитикам необходимо сопоставить 
общую выручку от продажи билетов с условными затратами на выполнение рейсов 
(приняв стоимость одной минуты полета за 1000 рублей). 
Используя обобщенные табличные выражения, создайте цепочку из двух временных слоев:
•	В первом слое на основе таблицы билетов (ticket) и таблицы вылетов (flight) 
рассчитайте суммарную выручку по каждому уникальному номеру маршрута (route_id).
•	Во втором слое на основе таблицы вылетов (flight) и таблицы маршрутов (route) 
рассчитайте суммарную длительность в минутах всех выполненных и запланированных рейсов для каждого маршрута.
В основном запросе объедините оба слоя с таблицей маршрутов (route), выведите номер рейса (route_no), 
общую выручку, общие расчетные затраты и итоговую чистую прибыль направления.
*/

with ticket_sum as (
select f.route_id, sum(t.price) as price_r from flight f join ticket t on t.flight_id = f.flight_id
group by f.route_id
),
duration as(
select f.route_id, sum(r.duration_min) as sum_dur from flight f join route r on r.route_id = f.route_id
group by f.route_id
)
select route_no, coalesce(t.price_r,0) as revenue, (coalesce(d.sum_dur,0) * 1000) as minus, 
(coalesce(t.price_r,0) - (coalesce(d.sum_dur,0) * 1000)) as total_amount from route r 
left join ticket_sum t on t.route_id = r.route_id
left join duration d on d.route_id = r.route_id;

/*
Задание 6
Коммерческий департамент распределяет бюджет на техническое обслуживание воздушных судов и 
хочет оценить реальный вклад каждого лайнера в доходы компании. 
Аналитикам необходимо рассчитать, какую долю (в процентах) занимает выручка конкретного самолета 
в общей структуре доходов авиакомпании. 
Используя обобщенное табличное выражение, подготовьте временный слой на основе 
таблицы билетов (ticket) и таблицы вылетов (flight), рассчитав суммарную выручку отдельно 
для каждого идентификатора самолета (airplane_id). 
В основном запросе, соединив полученный слой с таблицей самолетов (airplane), 
выведите бренд, модель лайнера и долю его выручки в процентах от общей суммы 
всех проданных билетов авиакомпании.
*/

with airplane_amount as(
select f.airplane_id, sum(t.price) as sum_price from flight f join ticket t on t.flight_id = f.flight_id
group by f.airplane_id
)
select a.brand, a.model, 
round(100 * am.sum_price / (select sum(sum_price) from airplane_amount),2) as percent 
from airplane_amount as am 
join airplane a on a.airplane_id = am.airplane_id; 

/*
Задание 7
Служба бортового сервиса организует премиальное обслуживание в полете для самых юных путешественников. 
Для всех детей, отправляющихся в длительные перелеты, авиакомпания централизованно включает в 
состав заказа специальный детский набор. Стоимость набора составляет 2500 рублей, однако для клиента 
он должен быть бесплатным. 
Используя обобщенное табличное выражение, сформируйте временный слой идентификаторов билетов (ticket_id) 
на основе таблиц билетов (ticket), пассажиров (passenger) и маршрутов (route), 
отобрав билеты детей на дальних маршрутах (расстояние превышает 4000 км).
В основном запросе обновите таблицу билетов (ticket): пропишите стоимость дополнительных услуг (service_price) 
в размере 2500 рублей, но одновременно предоставьте скидку на эту же сумму, 
уменьшив поле фактического тарифа (actual_rate) на 2500 рублей, 
чтобы итоговая финальная стоимость билета (price) осталась неизменной.
*/

begin;

with child_ticket as (
select t.ticket_id from ticket t join passenger p on p.passenger_id = t.passenger_id
join flight f on f.flight_id = t.flight_id
join route r on r.route_id = f.route_id
where r.distance_km > 4000 and p.category_name = 'Ребенок'
)
update ticket
set service_price = 2500, actual_rate = actual_rate - 2500
where ticket_id in (select ticket_id from child_ticket)

returning
    t.ticket_id,
    t.actual_rate,
    t.service_price,
    t.price;

rollback;

