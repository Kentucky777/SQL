-- ----------------------------------------------------------------------------
-- 2. СОЗДАНИЕ ТАБЛИЦ (DDL)
-- ----------------------------------------------------------------------------
CREATE TABLE country (
    country_id INT,
    country_name VARCHAR(100) NOT NULL
);

CREATE TABLE city (
    city_id INT,
    country_id INT NOT NULL,
    city_name VARCHAR(100) NOT NULL
);

CREATE TABLE airport (
    airport_id INT,
    city_id INT NOT NULL,
    airport_code CHAR(3) NOT NULL,
    airport_name VARCHAR(150) NOT NULL
);

CREATE TABLE airplane (
    airplane_id INT,
    brand VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    range_km INT NOT NULL,
    airplane_class VARCHAR(50) NOT NULL
);

CREATE TABLE seat (
    seat_id INT,
    airplane_id INT NOT NULL,
    seat_no VARCHAR(10) NOT NULL,
    fare_conditions VARCHAR(50) NOT NULL
);

CREATE TABLE route (
    route_id INT,
    departure_airport_id INT NOT NULL,
    arrival_airport_id INT NOT NULL,
    route_no VARCHAR(20) NOT NULL,
    duration_min INT NOT NULL,
    distance_km INT NOT NULL,
    schedule_pattern VARCHAR(7) NOT NULL
);

CREATE TABLE flight (
    flight_id INT,
    route_id INT NOT NULL,
    airplane_id INT NOT NULL,
    scheduled_departure TIMESTAMP NOT NULL
);

CREATE TABLE history (
    history_id INT,
    flight_id INT NOT NULL,
    status_name VARCHAR(100) NOT NULL,
    status_time TIMESTAMP NOT NULL
);

CREATE TABLE passenger (
    passenger_id INT,
    full_name VARCHAR(150) NOT NULL,
    passport_no VARCHAR(50) NOT NULL,
    birth_date DATE NOT NULL,
    gender CHAR(1) NOT NULL,
    category_name VARCHAR(50) NOT NULL
);

CREATE TABLE booking (
    booking_id INT,
    booking_date DATE NOT NULL,
    total_amount NUMERIC(10,2) NOT NULL
);

-- Таблица объединяет поля early_rate (из 2.2) и base_rate (из 2.3–2.5)
CREATE TABLE ticket (
    ticket_id INT,
    booking_id INT NOT NULL,
    passenger_id INT NOT NULL,
    flight_id INT NOT NULL,
    sale_date DATE NOT NULL,
    days_before_flight INT NOT NULL,
    early_rate NUMERIC(10,2) NOT NULL,
    base_rate NUMERIC(10,2) NOT NULL,
    actual_rate NUMERIC(10,2) NOT NULL,
    baggage_price NUMERIC(10,2) NULL,
    service_price NUMERIC(10,2) NULL,
    discount_percent INT NULL,
    price NUMERIC(10,2) NOT NULL
);

CREATE TABLE boarding (
    boarding_id INT,
    ticket_id INT NOT NULL,
    seat_id INT NOT NULL,
    boarding_no INT NOT NULL,
    registration_time TIMESTAMP NOT NULL
);

